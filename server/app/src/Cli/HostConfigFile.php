<?php

declare(strict_types=1);

namespace Linkrot\Cli;

use InvalidArgumentException;
use Linkrot\Config;
use Linkrot\PhpFile;

/**
 * Writes config.php of a host: the values that are set, and every other option with its default, commented out. The file
 * is generated, so it says so at the top, loudly: what is only a comment is not kept the next time it is written.
 */
final class HostConfigFile
{
    /** key => what it does; the order is the order in the file. Every option of Config::fromArray() is here (a test checks). */
    public const array DOC = [
        'email' => 'the one address that may get a code to manage tokens by mail; needs mail.from in global-config.php',
        'max_rm_after' => 'cap for any requested lifetime (1000y: practically none)',
        'default_rm_after' => 'lifetime if the client names none',
        'default_uses' => 'download limit if the client names none, null: unlimited',
        'max_file_size' => 'largest single file in bytes, 0: unlimited',
        'quota' => 'most data the host may hold: "100gb", "1tb" or bytes, 0: unlimited',
        'chunk_size' => 'bytes per upload chunk, 10-100 MB',
        'cleanup_interval' => 'minimum time between lazy cleanups',
        'upload_timeout' => 'unfinished uploads without activity are removed after this',
        'orphan_row_timeout' => 'grace period for rows without data and for expired or used-up files',
        'rate_limit_attempts' => 'failed attempts per window before a client address is blocked',
        'rate_limit_window' => 'that window in seconds',
        'download_mode' => "'xaccel' (nginx hands out the file) or 'php' (development only)",
    ];

    private const string BANNER = <<<'TXT'
        <?php

        /*
         * ##########################################################################################
         * ##                                                                                      ##
         * ##   THIS FILE IS GENERATED by app/bin/hosts. IT IS REWRITTEN FROM ITS VALUES.          ##
         * ##                                                                                      ##
         * ##   EVERYTHING THAT IS ONLY A COMMENT MIGHT BE GONE THE NEXT TIME: your own notes,     ##
         * ##   the layout, and the defaults shown below (they follow the release).                ##
         * ##                                                                                      ##
         * ##   To set an option, add a line `'name' => value,` (or uncomment one). Lines that     ##
         * ##   set a value are kept; nothing else is. Put notes somewhere else.                   ##
         * ##                                                                                      ##
         * ##########################################################################################
         */

        return [
        TXT;

    /**
     * The text of a config.php with these values set.
     *
     * @param array<array-key, mixed> $values
     */
    public static function render(array $values): string
    {
        $defaults = self::defaults();
        $lines = [self::BANNER];
        foreach (self::DOC as $key => $doc) {
            $lines[] = '';
            $lines[] = "    // $doc";
            $lines[] = array_key_exists($key, $values)
                ? "    '$key' => " . self::export($values[$key]) . ','
                : "    // '$key' => " . self::export($defaults[$key]) . ',';
        }
        $lines[] = '];';

        return implode("\n", $lines) . "\n";
    }

    /**
     * Rewrites the file from the values it sets. The old file is kept as config.php.bak (it may have had comments).
     *
     * @return bool false if the file would not change
     *
     * @throws InvalidArgumentException if the file is not a valid configuration: nothing is written then
     */
    public static function rewrite(string $file, string $baseUrl = 'https://localhost'): bool
    {
        return self::write($file, self::values($file), $baseUrl);
    }

    /**
     * Writes the file with these values; the result is checked as the server would load it first.
     *
     * @param array<array-key, mixed> $values
     *
     * @return bool false if the file would not change
     */
    public static function write(string $file, array $values, string $baseUrl = 'https://localhost'): bool
    {
        Config::fromArray($values, $baseUrl);
        $text = self::render($values);
        $old = is_file($file) ? file_get_contents($file) : null;
        if ($old === $text) {
            return false;
        }
        if ($old !== null && !copy($file, $file . '.bak')) {
            throw new InvalidArgumentException("cannot write {$file}.bak");
        }
        $mode = $old === null ? 0o644 : (fileperms($file) & 0o777);
        $tmp = $file . '.tmp' . bin2hex(random_bytes(3));
        if (file_put_contents($tmp, $text) === false || !chmod($tmp, $mode) || !rename($tmp, $file)) {
            @unlink($tmp);
            throw new InvalidArgumentException("cannot write $file");
        }

        return true;
    }

    /**
     * The values a config.php sets, as they are in the file.
     *
     * @return array<array-key, mixed>
     *
     * @throws InvalidArgumentException
     */
    public static function values(string $file, string $baseUrl = 'https://localhost'): array
    {
        $values = PhpFile::load($file, 'config', true);
        if (!is_array($values)) {
            throw new InvalidArgumentException("config: $file must return an array");
        }
        Config::fromArray($values, $baseUrl);

        return $values;
    }

    /** @return array<string, mixed> */
    public static function defaults(): array
    {
        $d = new Config('https://localhost');

        return [
            'email' => null,
            'max_rm_after' => $d->maxRmAfter,
            'default_rm_after' => $d->defaultRmAfter,
            'default_uses' => $d->defaultUses,
            'max_file_size' => $d->maxFileSize,
            'quota' => $d->quota,
            'chunk_size' => $d->chunkSize,
            'cleanup_interval' => $d->cleanupInterval,
            'upload_timeout' => $d->uploadTimeout,
            'orphan_row_timeout' => $d->orphanRowTimeout,
            'rate_limit_attempts' => $d->rateLimitAttempts,
            'rate_limit_window' => $d->rateLimitWindow,
            'download_mode' => $d->downloadMode->value,
        ];
    }

    private static function export(mixed $value): string
    {
        return $value === null ? 'null' : var_export($value, true);
    }
}
